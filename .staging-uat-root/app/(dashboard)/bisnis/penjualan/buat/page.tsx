function mergeLegacyReferenceNotes(reference: string, body: string): string {
  if (!reference) return body;
  return body ? `${reference}\n${body}` : reference;
}

function userMemoFromBody(body: string): string {
  return stripPosMetaFromNotes(body);
}

function notesWithPreservedPosMeta(memo: string, posMeta: PosMeta | null): string | undefined {
  const trimmed = memo.trim();
  if (!posMeta) return trimmed || undefined;
  return buildPosNotes(posMeta, trimmed || undefined);
}

function resolveFormStoreWarehouse(
  stores: Store[],
  so?: SalesOrder | null,
  inv?: Pick<Invoice, "store"> | null,
): { store: string; warehouse: string } {
  const store =
    (inv ? resolveStoreIdFromInvoice(inv, so, stores) : undefined) ??
    (so ? resolveStoreIdFromSalesOrder(so, stores) : undefined) ??
    "";
  const warehouse = so?.warehouse ?? "";
  return { store, warehouse };
}

function inferPaymentTermId(
  terms: PaymentTerm[],
  orderDate: string,
  dueDate?: string,
): string {
  if (!terms.length || !orderDate) return "";
  const order = orderDate.slice(0, 10);
  const due = dueDate?.slice(0, 10);
  if (!due || due === order) {
    return terms.find((t) => t.days === 0)?.id ?? "";
  }
  const diffDays = Math.round(
    (new Date(due).getTime() - new Date(order).getTime()) / 86400000,
  );
  const exact = terms.find((t) => t.days === diffDays);
  if (exact) return exact.id;
  const credit = terms.filter((t) => t.days > 0);
  if (!credit.length) return "";
  const closest = credit.reduce((best, t) =>
    Math.abs(t.days - diffDays) < Math.abs(best.days - diffDays) ? t : best,
  );
  return closest.id;
}

