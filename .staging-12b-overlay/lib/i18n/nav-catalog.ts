export function hrefToNavKey(href: string): string {
  return href.replace(/^\//, "").replace(/\//g, "_");
}

export function translateNavLabel(locale: Locale, href: string, fallback: string): string {
  const key = hrefToNavKey(href);
  return NAV_ITEMS[locale][key] ?? NAV_ITEMS.id[key] ?? fallback;
}

export function translateNavSection(locale: Locale, sectionKey: string, fallback: string): string {
  return NAV_SECTIONS[locale][sectionKey] ?? NAV_SECTIONS.id[sectionKey] ?? fallback;
}

export function translateHubDescription(locale: Locale, href: string, label: string): string {
  if (locale === "en") return `Open ${label}`;
  return `Buka ${label}`;
}
